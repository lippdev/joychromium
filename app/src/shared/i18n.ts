const tables: Record<Language, Record<string, string>> = { en, "pt-BR": ptBR };

export function t(language: string | undefined, key: string): string {
  const table = tables[(language === "en" ? "en" : "pt-BR") as Language];
  return table[key] ?? en[key] ?? key;
}

/** Every key with its English text: the pages translate themselves from this table. */
export function dictionary(language: string | undefined): Record<string, string> {
  return { ...en, ...tables[(language === "en" ? "en" : "pt-BR") as Language] };
}
